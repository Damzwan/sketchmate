// Ionic component trimming (P2.1).
//
// `@ionic/vue/dist/index.js` is a single pre-bundled module with ~130
// module-scope `defineCustomElement()` side effects, so no bundler can
// tree-shake it. This plugin resolves the `@ionic/core/components/ion-*.js`
// implementations of every component the app never renders to a generated
// no-op stub, which keeps the implementations and their CSS out of the graph.
//
// The scan runs at config time, not via an npm lifecycle hook, so `vite build`,
// `vite dev` and `pnpm verify` can never run against a stale used-set.
//
// Dev safety net: each stub registers a custom element for its own tag that
// logs when it is actually connected to the DOM. That fires only when a stubbed
// component really renders — unlike a warning in `defineCustomElement`, which
// `@ionic/vue` calls for every wrapper at import time regardless of use.

import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);

// Components created through Ionic's imperative controllers, or composed
// internally by other components' shadow DOM, never appear in a template scan.
// They must be listed by hand. This list is the risky part of the technique.
const ALLOWLIST = [
	"ion-action-sheet", // actionSheetController
	"ion-alert", // alertController
	"ion-backdrop", // used internally by modal / popover / loading
	"ion-loading", // loadingController
	"ion-modal", // modalController
	"ion-picker", // pickerController
	"ion-picker-column", // composed by ion-picker
	"ion-picker-column-option", // composed by ion-picker-column
	"ion-popover", // popoverController
	"ion-ripple-effect", // composed by ion-button / ion-item in MD mode
	"ion-toast", // toastController (src/service/toast.service.ts)
];

const KEBAB_TAG = /<(ion-[a-z0-9-]+)/g;
const PASCAL_TAG = /<(Ion[A-Z][A-Za-z0-9]*)/g;

function pascalToKebab(name) {
	return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function collectVueFiles(dir, out = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		if (entry.name === "node_modules" || entry.name === "generated") continue;
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) collectVueFiles(full, out);
		else if (entry.name.endsWith(".vue")) out.push(full);
	}
	return out;
}

function scanUsedComponents(srcDir) {
	const used = new Set(ALLOWLIST);
	for (const file of collectVueFiles(srcDir)) {
		const content = fs.readFileSync(file, "utf-8");
		for (const m of content.matchAll(KEBAB_TAG)) used.add(m[1]);
		for (const m of content.matchAll(PASCAL_TAG)) used.add(pascalToKebab(m[1]));
	}
	return used;
}

function listCoreComponents() {
	let componentsDir;
	try {
		componentsDir = path.join(
			path.dirname(require.resolve("@ionic/core/package.json")),
			"components",
		);
	} catch {
		return [];
	}
	if (!fs.existsSync(componentsDir)) return [];
	return fs
		.readdirSync(componentsDir)
		.filter((f) => f.startsWith("ion-") && f.endsWith(".js"))
		.map((f) => f.slice(0, -3));
}

function stubSource(tag) {
	return `// AUTO-GENERATED by scripts/vite-ionic-trim.mjs — do not edit.
// <${tag}> is not rendered anywhere in src/**/*.vue and is not on the
// controller allowlist, so its @ionic/core implementation was replaced by this
// no-op. If the dev guard below fires, add "${tag}" to ALLOWLIST in
// scripts/vite-ionic-trim.mjs — otherwise it is broken in production builds.
export const defineCustomElement = () => {
	if (!import.meta.env.DEV) return;
	if (typeof customElements === "undefined") return;
	if (customElements.get("${tag}")) return;
	customElements.define(
		"${tag}",
		class extends HTMLElement {
			connectedCallback() {
				console.error(
					"[Ionic Trim] <${tag}> rendered, but its implementation was stubbed " +
						"out of the bundle. Add it to ALLOWLIST in scripts/vite-ionic-trim.mjs.",
				);
			}
		},
	);
};
`;
}

function writeStubs(stubDir, tags) {
	fs.mkdirSync(stubDir, { recursive: true });
	const wanted = new Map(tags.map((t) => [`${t}.js`, stubSource(t)]));
	for (const existing of fs.readdirSync(stubDir)) {
		if (!wanted.has(existing)) fs.rmSync(path.join(stubDir, existing));
	}
	for (const [name, source] of wanted) {
		const file = path.join(stubDir, name);
		// Skip rewrites so the dev server does not see a spurious file change.
		const current = fs.existsSync(file) ? fs.readFileSync(file, "utf-8") : null;
		if (current !== source) fs.writeFileSync(file, source);
	}
}

/**
 * Returns the `resolve.alias` entries that stub out unused Ionic components.
 * Returns an empty array (no trimming, correct build) if @ionic/core cannot be
 * located, so a resolution problem degrades instead of breaking the app.
 */
export function ionicTrimAliases(root) {
	const all = listCoreComponents();
	const stubDir = path.join(root, "src/generated/ionic-stubs");

	if (all.length === 0) {
		console.warn("[ionic-trim] @ionic/core not found — trimming disabled.");
		fs.rmSync(stubDir, { recursive: true, force: true });
		return [];
	}

	const used = scanUsedComponents(path.join(root, "src"));
	const unused = all.filter((tag) => !used.has(tag));
	writeStubs(stubDir, unused);

	console.log(
		`[ionic-trim] ${all.length} components, ${all.length - unused.length} kept, ${unused.length} stubbed.`,
	);

	return unused.flatMap((tag) => {
		const replacement = path.join(stubDir, `${tag}.js`);
		return [
			{ find: `@ionic/core/components/${tag}.js`, replacement },
			{ find: `@ionic/core/components/${tag}`, replacement },
		];
	});
}
